import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Database from 'better-sqlite3';
import { stringify } from 'yaml';
import { groups, templates, users } from './catalog-fixtures.mjs';

// Local SQLite fixtures only: no production connection or credentials accepted.
const seed = 'analytics-demo-v1';
const databasePath = fileURLToPath(
  new URL('../.data/scaffolder.sqlite', import.meta.url),
);
if (!existsSync(databasePath)) {
  throw new Error(
    'Start this demo with yarn start once to initialize .data/scaffolder.sqlite, then run yarn seed:analytics.',
  );
}

assert.equal(templates.length, 50);
assert.equal(
  new Set(templates.map(template => template.metadata.name)).size,
  50,
);
assert.equal(users.length, 100);
assert.equal(new Set(users.map(user => user.metadata.name)).size, 100);
const writeEntities = (path, entities) =>
  writeFileSync(
    new URL(path, import.meta.url),
    '# Generated by yarn seed:analytics.\n' +
      entities.map(entity => stringify(entity)).join('---\n'),
  );
writeEntities('../examples/templates.yaml', templates);
writeEntities('../examples/users.yaml', users);
writeEntities('../examples/groups.yaml', groups);

const sqlDate = time =>
  new Date(time).toISOString().replace('T', ' ').replace('Z', '');
const now = Date.now();
const today = Date.parse(new Date(now).toISOString().slice(0, 10));
let index = 0;
const tasks = templates.flatMap((template, templateIndex) => {
  // A few popular templates and a longer tail, with 250 executions in total.
  const count =
    templateIndex < 10
      ? [22, 16, 12, 10, 8, 7, 6, 5, 4, 3][templateIndex]
      : 1 + ((templateIndex * 3) % 7);
  return Array.from({ length: count }, () => {
    const n = index++;
    const user = users[(n % 3 === 0 ? n : Math.ceil(n / 2)) % users.length];
    const bucket = (n * 7 + templateIndex * 13 + Math.floor(n / 3)) % 10;
    const status =
      bucket < 7 ? 'completed' : bucket < 9 ? 'failed' : 'cancelled';
    const durationMs = 1000 + ((n * 7919 + templateIndex * 17011) % 299000);
    // Spread runs over the default 30-day dashboard window.
    const day = today - (n % 30) * 86400000;
    const createdAt = Math.min(
      day + (8 + (n % 12)) * 3600000 + n * 1000,
      now - durationMs - 60000,
    );
    const hex = createHash('sha256').update(`${seed}:${n}`).digest('hex');
    const id = `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(
      13,
      16,
    )}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
    return {
      id,
      status,
      createdAt,
      finishedAt: createdAt + durationMs,
      createdBy: `user:default/${user.metadata.name}`,
      spec: {
        apiVersion: template.apiVersion,
        steps: template.spec.steps,
        output: template.spec.output,
        parameters: {
          seconds: Math.min(60, Math.ceil(durationMs / 1000)),
          outcome: status === 'failed' ? 'failure' : 'success',
          analyticsSeed: seed,
        },
        user: { ref: `user:default/${user.metadata.name}`, entity: user },
        templateInfo: {
          entityRef: `template:default/${template.metadata.name}`,
          baseUrl: new URL('../examples/templates.yaml', import.meta.url).href,
          entity: { metadata: template.metadata },
        },
      },
    };
  });
});
assert.equal(tasks.length, 250);
assert.equal(new Set(tasks.map(task => task.createdBy)).size, 100);
assert.equal(
  new Set(tasks.map(task => task.spec.templateInfo.entityRef)).size,
  50,
);

const db = new Database(databasePath, { fileMustExist: true, timeout: 10000 });
try {
  db.pragma('foreign_keys = ON');
  const existing = db.prepare('SELECT spec FROM tasks WHERE id = ?');
  const insert =
    db.prepare(`INSERT INTO tasks (id, spec, status, created_at, last_heartbeat_at, created_by)
    VALUES (@id, @spec, @status, @createdAt, @finishedAt, @createdBy)
    ON CONFLICT(id) DO UPDATE SET spec=excluded.spec, status=excluded.status,
      created_at=excluded.created_at, last_heartbeat_at=excluded.last_heartbeat_at,
      created_by=excluded.created_by`);
  const clearEvents = db.prepare('DELETE FROM task_events WHERE task_id = ?');
  const event = db.prepare(
    'INSERT INTO task_events (task_id, body, event_type, created_at) VALUES (?, ?, ?, ?)',
  );
  db.transaction(() => {
    for (const task of tasks) {
      const previous = existing.get(task.id);
      if (
        previous &&
        JSON.parse(previous.spec).parameters?.analyticsSeed !== seed
      ) {
        throw new Error(`Refusing to overwrite non-fixture task ${task.id}`);
      }
      insert.run({
        ...task,
        spec: JSON.stringify(task.spec),
        createdAt: sqlDate(task.createdAt),
        finishedAt: sqlDate(task.finishedAt),
      });
      clearEvents.run(task.id);
      event.run(
        task.id,
        JSON.stringify({
          message: 'Project initialization started',
          stepId: 'run',
          status: 'processing',
        }),
        'log',
        sqlDate(task.createdAt),
      );
      event.run(
        task.id,
        JSON.stringify({
          message: `Project initialization ${task.status}`,
          stepId: 'run',
          status: task.status,
        }),
        'log',
        sqlDate(task.finishedAt),
      );
      if (task.status === 'cancelled') {
        event.run(
          task.id,
          JSON.stringify({
            message: 'Execution cancelled by the requester',
            stepId: 'run',
            status: 'cancelled',
          }),
          'cancelled',
          sqlDate(task.finishedAt),
        );
      }
      event.run(
        task.id,
        JSON.stringify({
          message: `Project setup ${task.status}`,
          status: task.status,
          ...(task.status === 'completed'
            ? {
                output: {
                  text: [
                    {
                      title: 'Project setup',
                      content:
                        'Your execution is available in the Template Pulse dashboard.',
                    },
                  ],
                },
              }
            : {}),
          ...(task.status === 'failed'
            ? {
                error: {
                  name: 'Error',
                  message:
                    'Project initialization failed: configuration validation did not pass.',
                },
              }
            : {}),
        }),
        'completion',
        sqlDate(task.finishedAt),
      );
    }
  })();
  const counts = Object.fromEntries(
    ['completed', 'failed', 'cancelled'].map(status => [
      status,
      tasks.filter(task => task.status === status).length,
    ]),
  );
  console.log(
    JSON.stringify(
      {
        executions: tasks.length,
        templates: templates.length,
        users: users.length,
        statuses: counts,
        dateRange: [
          new Date(today - 29 * 86400000).toISOString().slice(0, 10),
          new Date(today).toISOString().slice(0, 10),
        ],
      },
      null,
      2,
    ),
  );
  console.log(
    'Seeded local Scaffolder history. Existing non-fixture executions are preserved.',
  );
  console.log(
    'Rerunning refreshes the same 250 fixtures without duplicating tasks.',
  );
  console.log(
    'Open http://localhost:3000/template-pulse as Admin User and select Organization analytics.',
  );
} finally {
  db.close();
}
